package org.traccar.model;

public class DeviceAppearance {

    private String cardImage;
    private String marker3d;
    private String mapMarker;
    private String markerCategory;
    private String markerModel;
    private String markerColor;

    public String getCardImage() {
        return cardImage;
    }

    public void setCardImage(String cardImage) {
        this.cardImage = cardImage;
    }

    public String getMarker3d() {
        return marker3d;
    }

    public void setMarker3d(String marker3d) {
        this.marker3d = marker3d;
    }

    public String getMapMarker() {
        return mapMarker;
    }

    public void setMapMarker(String mapMarker) {
        this.mapMarker = mapMarker;
    }

    public String getMarkerCategory() {
        return markerCategory;
    }

    public void setMarkerCategory(String markerCategory) {
        this.markerCategory = markerCategory;
    }

    public String getMarkerModel() {
        return markerModel;
    }

    public void setMarkerModel(String markerModel) {
        this.markerModel = markerModel;
    }

    public String getMarkerColor() {
        return markerColor;
    }

    public void setMarkerColor(String markerColor) {
        this.markerColor = markerColor;
    }
}
